/** An exercise's display name in the viewer's language (custom names show as written). */
export function exerciseDisplayName(name: string | null | undefined, lang: string): string {
  if (!name) return "";
  return lang === "ar" ? (EXERCISE_NAMES_AR[name] ?? name) : name;
}
